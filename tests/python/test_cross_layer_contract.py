from __future__ import annotations

import json
import re
import tomllib
from pathlib import Path

from gi_scenario_core.contracts import PUBLIC_CONTRACTS, SCHEMA_VERSION
from gi_scenario_core.rpc_worker import RPCDispatcher

ROOT = Path(__file__).resolve().parents[2]
WORKER_EXECUTABLE = "gi-scenario-worker"


def _rust_allowed_methods() -> set[str]:
    source = (ROOT / "apps/desktop/src-tauri/src/rpc.rs").read_text(encoding="utf-8")
    match = re.search(
        r"const ALLOWED_METHODS:\s*&\[&str\]\s*=\s*&\[(.*?)\];",
        source,
        re.DOTALL,
    )
    assert match is not None
    return set(re.findall(r'"([a-z0-9_.]+)"', match.group(1)))


def test_desktop_allowlist_matches_worker_dispatcher(tmp_path):
    dispatcher = RPCDispatcher(data_root=tmp_path)
    try:
        assert _rust_allowed_methods() == set(dispatcher.methods)
    finally:
        dispatcher._executor.shutdown(wait=True)


def test_worker_executable_name_matches_python_tauri_ci_and_docs():
    pyproject = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    assert pyproject["project"]["scripts"][WORKER_EXECUTABLE] == (
        "gi_scenario_core.rpc_worker:main"
    )

    tauri_config = json.loads(
        (ROOT / "apps/desktop/src-tauri/tauri.conf.json").read_text(encoding="utf-8")
    )
    assert tauri_config["bundle"]["externalBin"] == [f"binaries/{WORKER_EXECUTABLE}"]

    worker_source = (ROOT / "apps/desktop/src-tauri/src/worker.rs").read_text(encoding="utf-8")
    assert f'const SIDECAR_NAME: &str = "{WORKER_EXECUTABLE}";' in worker_source

    ci = (ROOT / ".github/workflows/ci.yml").read_text(encoding="utf-8")
    assert f"binaries/{WORKER_EXECUTABLE}-${{target}}" in ci
    for document in (ROOT / "README.md", ROOT / "docs/platform-packaging.md"):
        assert f"binaries/{WORKER_EXECUTABLE}-$TARGET_TRIPLE" in document.read_text(
            encoding="utf-8"
        )


def test_renderer_cannot_submit_a_plaintext_wandb_credential():
    wizard = (ROOT / "apps/desktop/src/components/ObservabilityWizard.tsx").read_text(
        encoding="utf-8"
    )
    host = (ROOT / "apps/desktop/src-tauri/src/lib.rs").read_text(encoding="utf-8")
    assert 'type="password"' not in wizard
    assert "credential_store" not in wizard
    assert "credential_prompt_and_store" in wizard
    assert "credential_prompt_and_store" in host
    assert "secret: String" not in host


def test_published_schema_index_matches_public_contract_source():
    version_directory = ROOT / "schemas" / f"v{SCHEMA_VERSION}"
    index = json.loads((version_directory / "index.json").read_text(encoding="utf-8"))
    assert index["schema_version"] == SCHEMA_VERSION
    assert set(index["contracts"]) == set(PUBLIC_CONTRACTS)
    for name, filename in index["contracts"].items():
        schema = json.loads((version_directory / filename).read_text(encoding="utf-8"))
        assert schema["title"] == name

    generated = (ROOT / "apps/desktop/src/generated/contracts.ts").read_text(encoding="utf-8")
    assert "generated by scripts/generate_schemas.py" in generated
    assert f'export const CONTRACT_VERSION = "{SCHEMA_VERSION}" as const;' in generated
