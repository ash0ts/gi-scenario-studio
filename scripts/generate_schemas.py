#!/usr/bin/env python3
"""Publish the versioned public contracts for the desktop and integrations.

Pydantic is the single source of truth.  This script writes one JSON Schema per
contract plus a generated TypeScript module that turns those exact schemas into
Zod validators.  The files are deterministic and are replaced atomically so a
failed generation cannot leave a half-written contract set.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "python"))

from gi_scenario_core.contracts import SCHEMA_VERSION, public_schemas

DEFAULT_SCHEMA_DIR = ROOT / "schemas" / f"v{SCHEMA_VERSION}"
DEFAULT_TYPESCRIPT = ROOT / "apps" / "desktop" / "src" / "generated" / "contracts.ts"


def _atomic_write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    handle, temporary_name = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    temporary = Path(temporary_name)
    try:
        with os.fdopen(handle, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)


def _typescript_module(schemas: dict[str, dict[str, object]]) -> str:
    lines = [
        "/* This file is generated by scripts/generate_schemas.py. Do not edit. */",
        'import { z } from "zod";',
        "",
        f'export const CONTRACT_VERSION = "{SCHEMA_VERSION}" as const;',
        "",
    ]
    for name, schema in schemas.items():
        encoded = json.dumps(schema, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
        lines.extend(
            [
                f"export const {name}JsonSchema = {encoded} satisfies z.core.JSONSchema.JSONSchema;",
                f"export const {name}Schema = z.fromJSONSchema({name}JsonSchema);",
                f"export type {name} = z.infer<typeof {name}Schema>;",
                "",
            ]
        )
    lines.append(
        "export const publicContractSchemas = {\n"
        + "\n".join(f"  {name}: {name}Schema," for name in schemas)
        + "\n} as const;"
    )
    lines.append("")
    return "\n".join(lines)


def generate(schema_directory: Path, typescript_path: Path) -> list[Path]:
    schemas = dict(sorted(public_schemas().items()))
    written: list[Path] = []
    for name, schema in schemas.items():
        target = schema_directory / f"{name}.schema.json"
        _atomic_write(
            target, json.dumps(schema, indent=2, ensure_ascii=False, sort_keys=True) + "\n"
        )
        written.append(target)

    index = {
        "schema_version": SCHEMA_VERSION,
        "contracts": {name: f"{name}.schema.json" for name in schemas},
    }
    index_path = schema_directory / "index.json"
    _atomic_write(index_path, json.dumps(index, indent=2, sort_keys=True) + "\n")
    _atomic_write(typescript_path, _typescript_module(schemas))
    written.extend([index_path, typescript_path])
    return written


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--schema-directory", type=Path, default=DEFAULT_SCHEMA_DIR)
    parser.add_argument("--typescript", type=Path, default=DEFAULT_TYPESCRIPT)
    arguments = parser.parse_args()
    written = generate(arguments.schema_directory.resolve(), arguments.typescript.resolve())
    print(f"generated {len(written)} contract artifacts for schema {SCHEMA_VERSION}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
